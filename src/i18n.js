export function createTranslator(language) {
  return (message, values = {}) => (language === 'he' ? HEBREW[message] ?? message : message)
    .replace(/\{(\w+)\}/g, (match, key) => values[key] === undefined ? match : String(values[key]));
}

export function readLanguage() {
  try { return globalThis.localStorage?.getItem('watershed-language') === 'he' ? 'he' : 'en'; }
  catch { return 'en'; }
}

export function saveLanguage(language) {
  try { globalThis.localStorage?.setItem('watershed-language', language); } catch {}
}